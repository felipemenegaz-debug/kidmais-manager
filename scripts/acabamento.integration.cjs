/* eslint-disable @typescript-eslint/no-require-imports */
const assert = require('node:assert/strict'), fs = require('node:fs'), crypto = require('node:crypto');
const { Client } = require('pg');
async function main() {
    const state = JSON.parse(fs.readFileSync('.tmp/admin-contrato-resultados.json'));
    assert.match(state.banco, /^kidmais_funcional_\d+$/);
    const url = new URL(process.env.DATABASE_URL);
    url.pathname = '/' + state.banco;
    process.env.DATABASE_URL = url.toString();
    process.env.NODE_ENV = 'test';
    require('./pagamentos-test-support.cjs');
    const c = new Client({ connectionString: url.toString() });
    await c.connect();
    const admin = await require('./admin-test-support.cjs').autenticarTeste(c);
    const { operarContrato, fontesEdicao, detalheAdministrativo } = require('../lib/contratos/services/administrativo.service.ts');
    const { buscarVersaoPorId } = require('../lib/contratos/repositories');
    const { criarFechamentoPublicoComIdentidade } = require('../lib/fechamentos/services/fechamento-publico.service.ts');
    const { gerarContrato } = require('../lib/contratos/services/contrato.service.ts');
    const { calcularResumoComercial } = require('../lib/comercial/services');
    const { consultarDisponibilidadeData } = require('../lib/disponibilidade/services');
    const agenda = require('../lib/disponibilidade/repositories');
    const route = require('../app/api/admin/contratos/versoes/[versaoId]/route.ts');
    const editor = require('../app/api/admin/contratos/versoes/[versaoId]/edicao/route.ts');
    const ctx = { requestId: crypto.randomUUID(), ip: null, userAgent: 'Teste sintético acabamento' };
    const results = [];
    const ok = s => { results.push(s); console.log('OK', s); };
    const before = (await c.query('SELECT to_jsonb(p)::text AS row FROM pagamentos p ORDER BY id')).rows;
    const signedBefore = (await c.query("SELECT to_jsonb(v)::text AS row FROM contrato_versoes v WHERE status='ASSINADA' ORDER BY id")).rows;
    const config = (await c.query("SELECT id FROM configuracao_agenda WHERE codigo='TURNO_1' LIMIT 1")).rows[0].id;
    const pacote = (await c.query("SELECT id FROM pacotes WHERE codigo='COMPLETA'")).rows[0].id;
    const essencial = (await c.query("SELECT id FROM pacotes WHERE codigo='ESSENCIAL'")).rows[0].id;
    const digits = Array.from({ length: 9 }, () => crypto.randomInt(0, 10));
    for (const peso of [10, 11]) {
        const r = digits.reduce((s, d, i) => s + d * (peso - i), 0) * 10 % 11;
        digits.push(r === 10 ? 0 : r);
    }
    const tabela = (await calcularResumoComercial({ data: '2098-10-11', configuracaoAgendaId: config, pacoteId: pacote, convidados: 50 })).valorTotalTabela;
    const f = (await criarFechamentoPublicoComIdentidade({ dataEvento: '2098-10-11', horarioInicio: '11:00', horarioFim: '15:00', configuracaoAgendaId: config, pacoteId: pacote, convidados: 50, valorProposto: tabela, formaPagamentoPretendida: 'CARTAO_CIELO', identidade: { tipo: 'NOVO_CLIENTE' }, idadeAniversarianteEvento: 7, cliente: { nomeCompleto: 'Teste acabamento', cpf: digits.join(''), telefone: '11999998888', whatsapp: '11999998888', email: `${crypto.randomUUID()}@example.invalid`, cep: '01001000', logradouro: 'Rua Sintética', numero: '1', bairro: 'Centro', cidade: 'São Paulo', uf: 'SP' }, aniversariante: { nome: 'Aniversariante Sintético' } })).fechamento;
    const created = await gerarContrato({ fechamentoId: f.id }, { usuarioId: admin.usuarioId, origem: 'SISTEMA' });
    const vid = created.versao.id;
    const fresh = async (extra = {}) => { const src = await fontesEdicao(f.id), ff = src.fechamento, e = (await c.query('SELECT revisao FROM contrato_edicoes WHERE contrato_versao_id=$1', [vid])).rows[0]; return { acao: 'editar_festa', revisao: e.revisao, fonteHash: src.fonteHash, motivo: 'Ajuste por necessidade administrativa', pacoteId: ff.pacoteId, convidados: ff.convidados, dataEvento: ff.dataEvento, configuracaoAgendaId: ff.configuracaoAgendaId, horarioInicio: ff.horarioInicio.slice(0, 5), horarioFim: ff.horarioFim.slice(0, 5), adicionais: src.adicionais, idadeAniversarianteEvento: ff.idadeAniversarianteEvento, temaFesta: ff.temaFesta ?? '', buffetStatus: ff.buffetStatus, buffetSalgados: ff.buffetSalgados ?? '', buffetBebidas: ff.buffetBebidas ?? '', buffetDoces: ff.buffetDoces ?? '', buffetBolo: ff.buffetBolo ?? '', buffetOutros: ff.buffetOutros ?? '', observacoesEquipe: ff.observacoesEquipe ?? '', ...extra }; };
    const operate = body => operarContrato(vid, body, admin.token, ctx);
    let doc = await operate({ acao: 'gerar_pdf', revisao: 1 });
    await operate({ acao: 'revisar', revisao: 1, documentoId: doc.documentoId });
    let input = await fresh({ convidados: 60 });
    let r = await route.POST(admin.request('/api/admin/contratos/versoes/' + vid, 'POST', input), { params: Promise.resolve({ versaoId: vid }) });
    assert.equal(r.status, 200, JSON.stringify(await r.json()));
    let v = await buscarVersaoPorId(vid);
    assert.equal(v.numeroVersao, 1);
    assert.equal(v.snapshot.evento.convidados, 60);
    assert(v.snapshot.comercial.valorFinalContrato > 9290);
    assert.equal((await c.query('SELECT documento_revisado_id FROM contrato_edicoes WHERE contrato_versao_id=$1', [vid])).rows[0].documento_revisado_id, null);
    ok('HTTP autenticado: convidados recalculados, mesma V1 e revisão/PDF anterior invalidados');
    await assert.rejects(operate({ acao: 'revisar', revisao: 2, documentoId: doc.documentoId }));
    ok('PDF da revisão anterior não pode ser aprovado');
    await assert.rejects(operate(input));
    ok('edição com revisão/fonte antiga recusada');
    for (const n of [110, 130, 140, 67]) {
        await operate(await fresh({ convidados: n }));
        assert.equal((await buscarVersaoPorId(vid)).snapshot.evento.convidados, n);
        ok(`convidados ${n}: backend aceita e recalcula${n === 67 ? ' (manual fora dos atalhos)' : ''}`);
    }
    for (const n of [0, 49, 151, 60.1])
        await assert.rejects(operate(await fresh({ convidados: n })));
    ok('mínimo, máximo e inteiros validados no backend');
    await operate(await fresh({ pacoteId: essencial, convidados: 50, buffetStatus: 'PENDENTE' }));
    const menor = (await buscarVersaoPorId(vid)).snapshot.comercial.valorTabela;
    await operate(await fresh({ buffetStatus: 'DEFINIDO', buffetBolo: 'Chocolate' }));
    await assert.rejects(operate(await fresh({ pacoteId: pacote })));
    ok('troca de pacote exige revisão de buffet');
    await operate(await fresh({ pacoteId: pacote, buffetStatus: 'PENDENTE' }));
    v = await buscarVersaoPorId(vid);
    assert(v.snapshot.comercial.valorTabela > menor);
    assert.equal(v.snapshot.contratacao.buffet.bolo, null);
    ok('upgrade recalcula e limpa escolhas incompatíveis');
    await assert.rejects(operate(await fresh({ adicionais: [{ codigo: 'PENNE', quantidade: 1 }] })));
    await assert.rejects(operate(await fresh({ adicionais: [{ codigo: ' penne ', quantidade: 1 }] })));
    for(const codigo of ['COMBO_ADULTOS','COMBO_LANCHINHOS'])await assert.rejects(operate(await fresh({adicionais:[{codigo,quantidade:1}]})));
    ok('item/combos incluídos não viram cobrança duplicada, inclusive código normalizado');
    await operate(await fresh({ adicionais: [{ codigo: 'MESA_CAFE', quantidade: 1 }] }));
    v = await buscarVersaoPorId(vid);
    assert(v.snapshot.comercial.valorAdicionais > 0);
    await operate(await fresh({ adicionais: [] }));
    assert.equal((await buscarVersaoPorId(vid)).snapshot.comercial.valorAdicionais, 0);
    ok('adicional incluído e removido com recálculo oficial');
    for (const [forma, valor] of [['PIX_AVISTA', 8361], ['PIX_PARCELADO', 9011.3], ['CARTAO_CIELO', 9290]]) {
        await operate(await fresh({ comercial: { confirmarAprovacao: true, forma, baseNegociada: 9290, condicaoPix: forma === 'PIX_PARCELADO' ? { quantidadeParcelas: 3 } : null } }));
        assert.equal((await buscarVersaoPorId(vid)).snapshot.comercial.valorFinalContrato, valor);
        ok(`${forma}: base 9290 -> ${valor}`);
    }
    await assert.rejects(operate(await fresh({ comercial: { confirmarAprovacao: true, forma: 'CARTAO_CIELO', baseNegociada: 9290.001, condicaoPix: null } })));
    ok('negociação subcentavo recusada');
    await assert.rejects(operate({ ...await fresh(), saldo: 0 }));
    ok('campos técnicos/financeiros recusados no serviço');
    const src = await fontesEdicao(f.id);
    const cliente = src.cliente;
    const cadastro = Object.fromEntries(['nomeCompleto', 'rg', 'telefone', 'whatsapp', 'email', 'cep', 'logradouro', 'numero', 'complemento', 'bairro', 'cidade', 'uf'].map(k => [k, cliente[k] ?? '']));
    await operate(await fresh({ cliente: { ...cadastro, telefone: '11988887777' }, aniversariante: { nome: 'Nome corrigido sintético', dataNascimento: null } }));
    v = await buscarVersaoPorId(vid);
    assert.equal(v.snapshot.contratante.telefone, '11988887777');
    assert.equal((await fontesEdicao(f.id)).aniversariante.nome, 'Nome corrigido sintético');
    ok('CRM e aniversariante atualizados na mesma transação do snapshot');
    const sourceAntes = await fontesEdicao(f.id);
    await assert.rejects(operate(await fresh({ convidados: 70, cliente: { ...cadastro, email: 'invalido' } })));
    assert.deepEqual(await fontesEdicao(f.id), sourceAntes);
    ok('erro de cadastro não persiste alteração parcial no Fechamento');
    const guardado = await fresh();
    const revNoop = (await operate(guardado)).revisao;
    assert.equal((await operate(await fresh())).revisao, revNoop);
    ok('salvar sem mudanças não cria versão nem revisão documental desnecessária');
    const stale = await fresh();
    await require('../lib/clientes/services').atualizarClienteInterno(f.clienteId, { nomeCompleto: 'Atualizado no CRM' }, { origem: 'CRM_INTERNO', usuarioId: admin.usuarioId });
    await assert.rejects(operate(stale));
    await assert.rejects(operate({ acao: 'gerar_pdf', revisao: stale.revisao }));
    ok('mudança externa do CRM impede sobrescrita e documento desatualizado');
    await operate({ acao: 'salvar', revisao: stale.revisao, observacoesDocumentais: 'Fonte atualizada' });
    const concurrent = await fresh({ convidados: 60, comercial: { confirmarAprovacao: true, forma: 'CARTAO_CIELO', baseNegociada: null, condicaoPix: null } });
    const raced = await Promise.allSettled([operate(concurrent), operate(concurrent)]);
    assert.equal(raced.filter(x => x.status === 'fulfilled').length, 1);
    ok('duas edições concorrentes: uma vence e outra recebe conflito');
    const novaData = '2098-10-12', disponivel = await consultarDisponibilidadeData(novaData), periodo = disponivel.periodos.find(p => p.configuracaoId === config), horario = periodo.horarios.find(h => h.status === 'DISPONIVEL');
    assert(horario);
    await operate(await fresh({ dataEvento: novaData, horarioInicio: horario.inicio, horarioFim: horario.fim }));
    assert.equal((await buscarVersaoPorId(vid)).snapshot.evento.data, novaData);
    assert.equal((await fontesEdicao(f.id)).fechamento.dataEvento, novaData);
    ok('data pré-assinatura disponível aceita; Fechamento e documento coerentes');
    const newDate = '2098-10-13', av = await consultarDisponibilidadeData(newDate), hp = av.periodos.find(p => p.configuracaoId === config).horarios.find(h => h.status === 'DISPONIVEL');
    const lock = new Client({ connectionString: url.toString() });
    await lock.connect();
    await lock.query('BEGIN');
    await agenda.adquirirLockConfirmacaoAgenda(newDate, lock);
    const remarc = await fresh({ dataEvento: newDate, horarioInicio: hp.inicio, horarioFim: hp.fim });
    let settled = false;
    const pending = operate(remarc).then(() => ({ ok: true }), e => ({ error: e })).finally(() => { settled = true; });
    await new Promise(r => setTimeout(r, 180));
    assert.equal(settled, false);
    await agenda.criarBloqueioAgenda({ data: newDate, diaInteiro: true, motivo: 'Bloqueio sintético concorrente' }, lock);
    await lock.query('COMMIT');
    await lock.end();
    assert((await pending).error);
    assert.equal((await fontesEdicao(f.id)).fechamento.dataEvento, novaData);
    ok('remarcação pré-assinatura espera bloqueio concorrente e recusa data ocupada atomicamente');
    const foreign = (await c.query("SELECT v.id,v.contrato_id FROM contrato_versoes v JOIN contratos c ON c.id=v.contrato_id WHERE v.status='ASSINADA' AND c.id<>$1 ORDER BY numero_versao LIMIT 1", [state.contratoId])).rows[0];
    const body = { acao: 'nova_versao', tipo: 'NOVA_VERSAO', motivo: 'Necessidade administrativa' };
    const two = await Promise.all([operarContrato(foreign.id, body, admin.token, ctx), operarContrato(foreign.id, body, admin.token, ctx)]);
    assert.equal(two[0].versaoId, two[1].versaoId);
    await assert.rejects(operarContrato(two[0].versaoId, await fresh(), admin.token, ctx));
    ok('nova versão por iniciativa Kidmais idempotente; edição com fonte de outra contratação recusada');
    assert.equal((await c.query('SELECT count(*)::int AS n FROM contrato_assinaturas WHERE contrato_versao_id=$1', [two[0].versaoId])).rows[0].n, 0);
    assert.deepEqual((await c.query("SELECT to_jsonb(v)::text AS row FROM contrato_versoes v WHERE status='ASSINADA' ORDER BY id")).rows, signedBefore);
    assert.deepEqual((await c.query('SELECT to_jsonb(p)::text AS row FROM pagamentos p ORDER BY id')).rows, before);
    ok('V1 assinada preservada; V2 sem assinatura herdada; Pagamentos íntegros');
    const panel = await detalheAdministrativo(created.contrato.id);
    assert(panel.versoes[0].alteracoes.campos.length > 0);
    assert((await c.query("SELECT 1 FROM auditoria WHERE entidade_id=$1 AND acao='ALTERACAO_ADMINISTRATIVA' AND usuario_id=$2 AND dados_antes IS NOT NULL AND dados_depois IS NOT NULL", [f.id, admin.usuarioId])).rowCount);
    ok('diferenças reais e auditoria com usuário, antes/depois');
    const { NextRequest } = require('next/server');
    r = await route.POST(new NextRequest('http://localhost:3000/api/admin/contratos', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(await fresh()) }), { params: Promise.resolve({ versaoId: vid }) });
    assert.equal(r.status, 401);
    const h = { ...admin.headers() };
    delete h['x-csrf-token'];
    r = await route.POST(new NextRequest('http://localhost:3000/api/admin/contratos', { method: 'POST', headers: h, body: JSON.stringify(await fresh()) }), { params: Promise.resolve({ versaoId: vid }) });
    assert.equal(r.status, 403);
    ok('HTTP sem sessão e sem CSRF recusado');
    r = await editor.GET(admin.request('/api/admin/contratos/versoes/' + vid + '/edicao'), { params: Promise.resolve({ versaoId: vid }) });
    assert.equal(r.status, 200);
    assert.equal((await r.json()).data.fonte.fechamento.id, f.id);
    ok('fachada carrega domínios e catálogo com sessão real');
    fs.writeFileSync('.tmp/acabamento-resultados.json', JSON.stringify({ banco: state.banco, contratoId: created.contrato.id, versaoId: vid, checks: results }, null, 2));
    await c.end();
    if (globalThis.__kidmaisPgPool)
        await globalThis.__kidmaisPgPool.end();
}
main().catch(e => { console.error(e); process.exitCode = 1; setTimeout(() => process.exit(1), 100); });
